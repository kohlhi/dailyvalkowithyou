// ════════════════════════════════════════════════════════════
//   三、小狼系列（一個系列 = 一套圖 + 一張台詞表）
// ════════════════════════════════════════════════════════════
//
// 每個系列是一隻各自升級、各自進化的小狼。
// 這裡改了，所有使用者下次打開 App 就會看到（稱號、圖、場景都是即時讀這裡）。
//
// 推出新系列的步驟：
//   1. 把圖放進 public/heroes/ 底下（建議一個系列一個資料夾，例如 public/heroes/運動/）
//   2. 在下面的清單加一筆，「開放」寫 true
//   3. 在「五、角色台詞」加一張同樣「角色」名字的台詞表（不寫也行，會用共用台詞）
//   4. 推上去。舊使用者下次打開就會多一隻從 lv.1 開始的新小狼
//
// 注意：
//   • 「角色」是這個系列的代號，使用者的等級和進度靠它對應，取了就永遠不要改。
//   • 「開放: false」的系列不會出現；但已經在上面練過等級的舊使用者還是看得到，進度不會消失。
//   • 系列刪掉的話，已經有這隻狼的使用者會保留最後看到的樣子。要下架請改成「開放: false」。
//   • 階段的「等級」不寫就是 lv.1 / lv.10 / lv.25 / lv.45。
//   • 階段的「圖」和「場景」不寫，就沿用前一個階段的。

export interface 階段內容 {
  稱號: string
  /** 到這個等級進化；第一階固定從 lv.1 開始 */
  等級?: number
  /** 角色圖，可以放好幾張，每次隨機出現一張；不寫就沿用前一階 */
  圖?: string[]
  /** 首頁背景；不寫就沿用前一階 */
  場景?: string
}

export interface 系列內容 {
  /** 系列代號，對應「五、角色台詞」的哪一張表。取了就不要改 */
  角色: string
  /** 顯示用的系列名稱 */
  名稱: string
  /** false = 還沒上架 */
  開放: boolean
  技能: string[]
  階段: 階段內容[]
}


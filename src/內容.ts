//   {招呼}  早安／午安／晚安…      {稱號}  目前的階段稱號
//   {剩下}  今天的每日任務還剩幾個  {連續}  連續完成的天數
//   {天數}  這隻狼幾天沒完成任務    {等級}  目前等級
//   {任務}  任務名稱               {步驟}  步驟名稱
//   {次數}  記完是第幾次           {還差}  記完還差幾次
//   {exp}   這次拿到的經驗值
//   清單底部另外有：{完成} 完成幾個、{剩下} 還剩幾個、{總數} 一共幾個
//   打錯的變數會原封不動顯示出來，不會讓 App 壞掉。
//
// ── 開場：打開 App 時小狼說的第一句 ──
//   由上往下檢查，第一個「條件」全部符合的情境就用它，所以特別的放上面、「一般」放最後。
//   條件可以組合，沒寫的條件就不檢查。可以用的條件：
//     從沒完成: true          這隻狼還沒完成過任何任務
//     時段: [22, 24]          22:00～23:59（前面包含、後面不含；[22, 2] 會跨過午夜）
//     星期: [0, 6]            0 是星期日，6 是星期六
//     沒動: 3                 這隻狼 3 天以上沒完成任務
//     昨天有完成: true        這隻狼昨天有完成任務
//     連續: [3, 7, 30]        連續天數剛好是其中一個數字
//     每日剩至少: 1           今天的每日任務至少還剩 1 個
//     週任務剩至少: 1         這週的週任務至少還剩 1 個
//     今日完成: true          今天的每日任務全部完成
//     等級: [10, 24]          等級在 10～24 之間
//
// ── 階段：進化後的狼說的話 ──
//   「階段」由左到右對應 lv.1 / lv.10 / lv.25 / lv.45。
//   這一階有寫的台詞會「加入」整隻狼的台詞一起抽，每一句被抽到的機會是一般台詞的兩倍。
//   這一階沒寫就往前找最近一個有寫的階段，所以只寫第一階也沒問題。
//   開場的情境名字跟上面一樣，就是替那個情境多加幾句；名字不一樣，就是這一階才有的新情境（會優先檢查）。
//   「進化」只在剛進化到那一階時說一次，不會往前找。
//
// ── 不會一直重複 ──
//   同一類最近說過的幾句會先跳過，所以同一類寫越多句，越不容易聽到重複的。

export interface 台詞條件 {
  從沒完成?: boolean
  時段?: [number, number]
  星期?: number[]
  沒動?: number
  昨天有完成?: boolean
  連續?: number[]
  每日剩至少?: number
  週任務剩至少?: number
  今日完成?: boolean
  等級?: [number, number]
}

export interface 情境台詞 {
  情境: string
  條件: 台詞條件
  台詞: string[]
}

export interface 台詞組 {
  /** 打開 App 時的第一句 */
  開場?: 情境台詞[]
  /** 首頁點一下小狼 */
  點小狼?: string[]
  /** 完成一般任務前的確認 */
  確認?: string[]
  /** 有次數的任務，還沒到最後一次 */
  記一次?: string[]
  /** 有次數的任務，最後一次 */
  最後一次?: string[]
  /** 步驟打勾前的確認 */
  步驟?: string[]
  /** 最後一個步驟 */
  最後一步?: string[]
  /** 完成任務之後 */
  完成後?: string[]
  /** 剛進化到這一階時 */
  進化?: string[]
  /** 升級畫面 */
  升級?: string[]
  /** 切換到這隻狼時 */
  切換?: string[]
  /** 任務清單底部，依清單與進度分 */
  清單底部?: 清單底部台詞
}

export interface 清單進度台詞 {
  沒開始?: string[]
  進行中?: string[]
  剩一個?: string[]
  全部完成?: string[]
}

export interface 清單底部台詞 {
  /** 清單裡一個任務都沒有 */
  空的?: string[]
  每日?: 清單進度台詞
  每週?: 清單進度台詞
  成就?: 清單進度台詞
}

export interface 角色台詞表 extends 台詞組 {
  /** 由左到右對應第 1～4 階 */
  階段?: 台詞組[]
}


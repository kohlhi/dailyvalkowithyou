//   三之三、你自己的 lofi 音樂
// ════════════════════════════════════════════════════════════
//
// 怎麼加：
//   1. 把音樂檔丟進 public/lofi/ 資料夾
//   2. 在下面的清單加一行
//   3. commit 推上去就會出現在「陪伴」頁
//
// 注意事項：
//   • 格式用 **mp3** 最安全，m4a／aac 也可以。不要用 ogg 或 opus，iOS 支援不穩。
//   • 128kbps 大約一分鐘 1MB。放五六首還好，別放三十首。
//   • 音樂不會被塞進安裝包（所以安裝還是很快），但**放過一次之後會存起來**，
//     之後離線也聽得到。
//   • **授權要看清楚**：你需要「可以放進 app 重新散布」的授權，
//     不是「可以免費聽」。CC0 最安全；CC-BY 可以用但一定要填「作者」欄位，
//     填了就會顯示在畫面上。
//
// 範例（把 // 拿掉就會生效）：
//   { 名稱: '雨天的咖啡廳', 檔名: 'rainy-cafe.mp3', 作者: 'Someone (CC-BY)' },

export interface 音樂內容 {
  名稱: string
  /** 檔名，放在 public/lofi/ 底下 */
  檔名: string
  /** 作者。CC-BY 這類授權一定要標，填了就會顯示在卡片上 */
  作者?: string
}

